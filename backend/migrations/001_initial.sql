CREATE TABLE usuarios (
 cod_identificador text PRIMARY KEY, txt_nome text NOT NULL, txt_email text NOT NULL UNIQUE,
 txt_senha_hash text NOT NULL, txt_perfil text NOT NULL CHECK(txt_perfil IN ('admin','staff','pending','blocked')),
 dat_cadastro timestamptz NOT NULL, txt_recuperacao_hash text
);
CREATE UNIQUE INDEX uq_usuario_responsavel ON usuarios(txt_perfil) WHERE txt_perfil='admin';
CREATE TABLE permissoes (txt_nome text PRIMARY KEY);
INSERT INTO permissoes VALUES ('cats.submit'),('cats.photos'),('cats.status'),('medical.read'),('medical.write'),('adoptions.lookup');
CREATE TABLE permissoes_usuarios (
 cod_usuario text REFERENCES usuarios(cod_identificador) ON DELETE CASCADE,
 txt_permissao text REFERENCES permissoes(txt_nome), PRIMARY KEY(cod_usuario,txt_permissao)
);
CREATE TABLE fichas_voluntarios (
 cod_usuario text PRIMARY KEY REFERENCES usuarios(cod_identificador), txt_cpf char(11) NOT NULL,
 txt_idade text NOT NULL, txt_endereco text NOT NULL, txt_telefone text NOT NULL,
 txt_ocupacao text NOT NULL DEFAULT '', txt_transporte text NOT NULL DEFAULT '',
 txt_experiencia text NOT NULL DEFAULT '', txt_animais text NOT NULL DEFAULT '', txt_habilidades text NOT NULL DEFAULT '',
 txt_dias text NOT NULL DEFAULT '', txt_horas text NOT NULL DEFAULT '', txt_frequencia text NOT NULL DEFAULT '',
 txt_preferencias text NOT NULL DEFAULT '', txt_motivacao text NOT NULL DEFAULT '',
 txt_compromisso text NOT NULL CHECK(txt_compromisso='Sim'), txt_regras text NOT NULL CHECK(txt_regras='Sim'),
 txt_assinatura text NOT NULL, dat_assinatura date
);
CREATE TABLE sessoes (cod_identificador text PRIMARY KEY, cod_usuario text NOT NULL REFERENCES usuarios(cod_identificador) ON DELETE CASCADE, dat_expiracao timestamptz NOT NULL);
CREATE INDEX idx_sessoes_expiracao ON sessoes(dat_expiracao);
CREATE TABLE limites_requisicoes (txt_chave text PRIMARY KEY, num_contagem integer NOT NULL, dat_expiracao timestamptz NOT NULL);
CREATE TABLE configuracoes (txt_chave text PRIMARY KEY, txt_valor text NOT NULL);
CREATE TABLE revisoes_estado (cod_identificador integer PRIMARY KEY CHECK(cod_identificador=1), num_versao integer NOT NULL CHECK(num_versao>0));
INSERT INTO revisoes_estado VALUES(1,1);
CREATE TABLE gatos (
 cod_identificador integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 txt_nome text NOT NULL, txt_idade text NOT NULL, txt_sexo text NOT NULL CHECK(txt_sexo IN ('Macho','Fêmea')),
 txt_personalidade text NOT NULL, txt_situacao text NOT NULL CHECK(txt_situacao IN ('Disponível','Em tratamento','Reservado','Adotado')),
 txt_historia text NOT NULL DEFAULT '', txt_cor text NOT NULL DEFAULT '', dat_entrada date,
 txt_local_resgate text NOT NULL DEFAULT '', txt_resgatante text NOT NULL DEFAULT '', txt_relato_resgate text NOT NULL DEFAULT '',
 num_foto_exemplo integer NOT NULL DEFAULT 0, cod_aprovador text REFERENCES usuarios(cod_identificador)
);
CREATE TABLE caracteristicas_gatos (cod_gato integer REFERENCES gatos(cod_identificador), num_posicao integer NOT NULL, txt_descricao text NOT NULL, PRIMARY KEY(cod_gato,num_posicao));
CREATE TABLE propostas_gatos (
 cod_identificador text PRIMARY KEY, cod_usuario text NOT NULL REFERENCES usuarios(cod_identificador),
 txt_situacao text NOT NULL CHECK(txt_situacao IN ('pending','approved','rejected')), num_versao integer NOT NULL DEFAULT 1,
 dat_cadastro timestamptz NOT NULL, cod_revisor text REFERENCES usuarios(cod_identificador), dat_revisao timestamptz, txt_motivo text NOT NULL DEFAULT '',
 txt_nome text NOT NULL, txt_idade text NOT NULL, txt_sexo text NOT NULL CHECK(txt_sexo IN ('Macho','Fêmea')), txt_personalidade text NOT NULL,
 txt_situacao_gato text NOT NULL CHECK(txt_situacao_gato IN ('Disponível','Em tratamento')), txt_historia text NOT NULL, txt_cor text NOT NULL,
 dat_entrada date NOT NULL, txt_local_resgate text NOT NULL, txt_resgatante text NOT NULL, txt_relato_resgate text NOT NULL,
 cod_gato_aprovado integer REFERENCES gatos(cod_identificador)
);
CREATE TABLE vacinas (
 cod_identificador bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, cod_gato integer NOT NULL REFERENCES gatos(cod_identificador), num_posicao integer NOT NULL,
 txt_descricao text NOT NULL, dat_data date NOT NULL, txt_situacao text NOT NULL, flg_realizado boolean NOT NULL DEFAULT false,
 dat_aplicacao date, txt_responsavel text NOT NULL DEFAULT '', dat_proxima_dose date, txt_comprovante text NOT NULL DEFAULT ''
);
CREATE TABLE tarefas_cuidados (
 cod_identificador bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, cod_gato integer NOT NULL REFERENCES gatos(cod_identificador), num_posicao integer NOT NULL,
 txt_descricao text NOT NULL, hor_horario time NOT NULL, flg_realizado boolean NOT NULL DEFAULT false
);
CREATE TABLE candidaturas_adocao (
 cod_identificador text PRIMARY KEY, txt_token_hash text NOT NULL UNIQUE, txt_cpf_hash text NOT NULL,
 cod_gato integer REFERENCES gatos(cod_identificador), num_etapa integer NOT NULL DEFAULT 0 CHECK(num_etapa BETWEEN -1 AND 4),
 dat_data date NOT NULL, txt_orientacao text NOT NULL DEFAULT '', txt_observacao text NOT NULL DEFAULT '', txt_motivo_reprovacao text NOT NULL DEFAULT '',
 flg_devolvido boolean NOT NULL DEFAULT false, num_versao integer NOT NULL DEFAULT 1, dat_cadastro timestamptz NOT NULL
);
CREATE INDEX idx_candidaturas_cpf ON candidaturas_adocao(txt_cpf_hash);
CREATE UNIQUE INDEX uq_gato_adocao_ativa ON candidaturas_adocao(cod_gato) WHERE num_etapa IN (3,4) AND NOT flg_devolvido;
CREATE TABLE respostas_entrevistas (
 cod_candidatura text REFERENCES candidaturas_adocao(cod_identificador), txt_pergunta text NOT NULL, txt_resposta text NOT NULL,
 PRIMARY KEY(cod_candidatura,txt_pergunta)
);
CREATE TABLE historico_etapas_adocao (
 cod_identificador bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, cod_candidatura text NOT NULL REFERENCES candidaturas_adocao(cod_identificador),
 num_etapa integer NOT NULL CHECK(num_etapa BETWEEN -1 AND 4), dat_data timestamptz NOT NULL, cod_usuario text NOT NULL REFERENCES usuarios(cod_identificador)
);
CREATE TABLE eventos_adocao (
 cod_identificador text PRIMARY KEY, cod_candidatura text NOT NULL REFERENCES candidaturas_adocao(cod_identificador),
 txt_tipo text NOT NULL CHECK(txt_tipo IN ('followup','return','term')), dat_data date NOT NULL,
 txt_anotacoes text NOT NULL, cod_usuario text NOT NULL REFERENCES usuarios(cod_identificador), dat_cadastro timestamptz NOT NULL
);
CREATE UNIQUE INDEX uq_candidatura_devolucao ON eventos_adocao(cod_candidatura) WHERE txt_tipo='return';
CREATE TABLE registros_clinicos (
 cod_identificador text PRIMARY KEY, cod_gato integer NOT NULL REFERENCES gatos(cod_identificador), txt_tipo text NOT NULL CHECK(txt_tipo IN ('treatment','application','note','completion')),
 cod_tratamento text, cod_usuario text NOT NULL REFERENCES usuarios(cod_identificador), dat_cadastro timestamptz NOT NULL,
 txt_descricao text NOT NULL DEFAULT '', dat_data date NOT NULL, hor_horario time, txt_dose text NOT NULL DEFAULT '',
 txt_frequencia text NOT NULL DEFAULT '', dat_fim_previsto date, txt_prescritor text NOT NULL DEFAULT '',
 txt_anotacoes text NOT NULL DEFAULT '', dat_dose_prevista timestamptz, num_intervalo_horas double precision CHECK(num_intervalo_horas BETWEEN 1 AND 168),
 UNIQUE(cod_identificador,cod_gato), FOREIGN KEY(cod_tratamento,cod_gato) REFERENCES registros_clinicos(cod_identificador,cod_gato),
 CHECK((txt_tipo IN ('application','completion')) = (cod_tratamento IS NOT NULL))
);
CREATE INDEX idx_registros_gato_cadastro ON registros_clinicos(cod_gato,dat_cadastro);
CREATE UNIQUE INDEX uq_registros_dose_prevista ON registros_clinicos(cod_tratamento,dat_dose_prevista) WHERE txt_tipo='application' AND dat_dose_prevista IS NOT NULL;
CREATE UNIQUE INDEX uq_tratamento_encerramento ON registros_clinicos(cod_tratamento) WHERE txt_tipo='completion';
CREATE TABLE anexos (
 cod_identificador text PRIMARY KEY, txt_tipo_vinculo text NOT NULL CHECK(txt_tipo_vinculo IN ('cat','video','term')),
 cod_gato integer REFERENCES gatos(cod_identificador), cod_candidatura text REFERENCES candidaturas_adocao(cod_identificador),
 txt_nome text NOT NULL, txt_tipo_midia text NOT NULL, bin_conteudo bytea NOT NULL CHECK(octet_length(bin_conteudo)<=8388608), dat_cadastro timestamptz NOT NULL,
 CHECK((txt_tipo_vinculo='cat' AND cod_gato IS NOT NULL AND cod_candidatura IS NULL) OR (txt_tipo_vinculo IN ('video','term') AND cod_candidatura IS NOT NULL AND cod_gato IS NULL))
);
CREATE TABLE fotos_gatos (cod_gato integer PRIMARY KEY REFERENCES gatos(cod_identificador), cod_anexo text NOT NULL UNIQUE REFERENCES anexos(cod_identificador));
CREATE TABLE campanhas (cod_identificador integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY, txt_descricao text NOT NULL, txt_endereco_web text NOT NULL);
CREATE TABLE fila_mensagens (
 cod_identificador text PRIMARY KEY, txt_destino text NOT NULL CHECK(txt_destino IN ('owner','volunteers')), txt_mensagem text NOT NULL,
 dat_cadastro timestamptz NOT NULL, dat_envio timestamptz, num_tentativas integer NOT NULL DEFAULT 0,
 dat_proxima_tentativa timestamptz NOT NULL DEFAULT '1970-01-01T00:00:00Z', txt_ultimo_erro text
);
CREATE INDEX idx_mensagens_pendentes ON fila_mensagens(dat_proxima_tentativa,dat_cadastro) WHERE dat_envio IS NULL;
CREATE TABLE envios_whatsapp (cod_identificador text PRIMARY KEY, txt_impressao_hash text NOT NULL);
CREATE TABLE entregas_whatsapp (
 cod_envio text REFERENCES envios_whatsapp(cod_identificador), txt_destinatario_hash text NOT NULL,
 txt_estado text NOT NULL CHECK(txt_estado IN ('sending','uncertain','accepted','rejected')),
 txt_identificador_meta text, dat_atualizacao timestamptz NOT NULL, PRIMARY KEY(cod_envio,txt_destinatario_hash)
);
